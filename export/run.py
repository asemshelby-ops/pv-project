"""Step 5: export both hybrid NASIM-GBT models to C and prove parity with Python.

    python -m export.run            (models of config.EXPORT_VARIANT / EXPORT_SEED)

Needs a finished `python -m eval.run` for that variant and seed (it reads the
tuned p thresholds and checks against the saved models). Steps:
  1. retrain both hybrid models from the same training days (training is
     deterministic) and check that they equal the models saved by eval.run;
  2. export each model with m2cgen (nested if/else in C), using `real`;
  3. write nasim_config.h from config.py, so C and Python share every constant;
  4. run the held-out test days through the Python detector and through the
     compiled C detector (double and float builds) and compare per sample:
     probability, alarms and every feature;
  5. report code and model sizes; write out/export/parity.md.
The C detector itself is export/c/nasim.c (hand-ported features, thermal step,
CUSUM core and alarm logic). No ESP32 firmware here (that is task 2).
"""
import json
import os
import pathlib
import shutil
import subprocess

import lightgbm as lgb
import m2cgen
import numpy as np
import pandas as pd

import config
from data import synth
from detect import gbt, stream
from detect.features import N2, N5, N10, feature_names
from eval.run import evaluate
from eval.split import split_days

C_DIR = pathlib.Path("export/c")
GEN_DIR = C_DIR / "generated"
OUT = pathlib.Path("out/export")
MODELS = [  # (tag, use_wind, row name in tuned.json); the first is the main model
    ("nowind", False, "NASIM-GBT (no wind)"),
    ("wind", True, "NASIM-GBT"),
]


# --- code generation -------------------------------------------------------------

def config_header():
    """nasim_config.h: every constant the C code needs, taken from config.py."""
    vals = {
        "DT_S": config.DT_S, "LAT": config.LAT, "LON": config.LON,
        "TILT_DEG": config.TILT_DEG, "AZIMUTH_DEG": config.AZIMUTH_DEG,
        "AREA_M2": config.AREA_M2, "HEAT_CAPACITY_J_K": config.HEAT_CAPACITY_J_K,
        "FAIMAN_U0": config.FAIMAN_U0, "FAIMAN_U1": config.FAIMAN_U1,
        "G_FLOOR": config.G_FLOOR, "CS_DIFFUSE_FRAC": config.CS_DIFFUSE_FRAC,
        "CUSUM_WIND_CONST": config.CUSUM_WIND_CONST,
        "CUSUM_WIND_TAU_MIN": config.CUSUM_WIND_TAU_MIN,
        "CUSUM_RES_TAU_MIN": config.CUSUM_RES_TAU_MIN,
        "HYBRID_CUSUM_K": config.HYBRID_CUSUM_K,
    }
    ints = {"MEDIAN_N": config.MEDIAN_N, "N2": N2, "N5": N5, "N10": N10,
            "SILENCE_N": gbt.SILENCE_N,
            "DET_RESET_AFTER_FAILS": config.DET_RESET_AFTER_FAILS}
    lines = ["/* GENERATED by export/run.py from config.py -- do not edit. */",
             "#ifndef NASIM_CONFIG_H", "#define NASIM_CONFIG_H"]
    lines += [f"#define NASIM_{k} {float(v)!r}" for k, v in vals.items()]
    lines += [f"#define NASIM_{k} {int(v)}" for k, v in ints.items()]
    lines += ["#endif", ""]
    return "\n".join(lines)


def model_source(clf, tag, names, p_threshold, source_note):
    """m2cgen C code for one model, with `real` and unique symbol names."""
    code = m2cgen.export_to_c(clf, function_name=f"nasim_score_{tag}")
    code = code.replace("sigmoid(", f"sigmoid_{tag}(").replace("double", "real")
    code = code.replace("exp(", "R_EXP(")          # expf in the float build
    code = code.replace(f"real sigmoid_{tag}(", f"static real sigmoid_{tag}(", 1)
    head = [f"/* GENERATED by export/run.py with m2cgen {m2cgen.__version__} -- do not edit.",
            f" * NASIM-GBT ({'with' if 'wind' in names else 'no'} wind), hybrid. {source_note}",
            " * input[] order: " + ", ".join(names),
            f" * output[1] = p(spike). Alarm rule: p >= {p_threshold!r} for "
            f"{config.GBT_PERSIST} consecutive samples.",
            " * Trained on SYNTHETIC data: retrain on real data before use. */",
            '#include "nasim.h"', ""]
    return "\n".join(head) + code


# --- compile and run ----------------------------------------------------------------

def find_gcc():
    gcc = os.environ.get("NASIM_GCC") or shutil.which("gcc")
    if gcc:
        return gcc
    root = pathlib.Path(os.environ.get("LOCALAPPDATA", "")) / "Microsoft/WinGet/Packages"
    hits = sorted(root.glob("BrechtSanders.WinLibs*/mingw64/bin/gcc.exe")) if root.exists() else []
    return str(hits[0]) if hits else None


def compile_parity(gcc, single, gen_dir=GEN_DIR, out=OUT):
    exe = out / f"parity_{'float' if single else 'double'}.exe"
    srcs = [C_DIR / "nasim.c", C_DIR / "parity_main.c",
            gen_dir / "nasim_model_nowind.c", gen_dir / "nasim_model_wind.c"]
    flags = ["-std=c99", "-O2", "-Wall", "-Wextra", f"-I{C_DIR}", f"-I{gen_dir}"]
    if single:
        flags += ["-DNASIM_FLOAT", "-fsingle-precision-constant"]
    subprocess.run([gcc, *flags, *map(str, srcs), "-o", str(exe), "-lm"], check=True)
    return exe


def object_sizes(gcc, single):
    """text + data bytes of each object (x86-64, -Os): an indication only; the
    ESP32 (Xtensa) size must be measured with its own toolchain (task 2)."""
    size_tool = pathlib.Path(gcc).with_name("size.exe")
    out = {}
    for src in (C_DIR / "nasim.c", GEN_DIR / "nasim_model_nowind.c",
                GEN_DIR / "nasim_model_wind.c"):
        obj = OUT / (src.stem + ("_f" if single else "_d") + ".o")
        flags = ["-std=c99", "-Os", "-c", f"-I{C_DIR}", f"-I{GEN_DIR}"]
        if single:
            flags += ["-DNASIM_FLOAT", "-fsingle-precision-constant"]
        subprocess.run([gcc, *flags, str(src), "-o", str(obj)], check=True)
        if size_tool.exists():
            r = subprocess.run([str(size_tool), str(obj)], capture_output=True, text=True,
                               check=True)
            text, data = (int(x) for x in r.stdout.splitlines()[1].split()[:2])
            out[src.name] = text + data
        else:
            out[src.name] = obj.stat().st_size
    return out


def write_input(days, path):
    """Test days as the C harness reads them, full double precision (repr)."""
    with open(path, "w") as fh:
        fh.write("new_day,T1,T2,T3,T4,T5,ta,g,wind,doy,minute\n")
        for new_day, s in stream.samples(days):
            vals = [*s.t_back, s.ta, s.g, s.wind]
            fh.write(f"{int(new_day)}," + ",".join(repr(float(v)) for v in vals)
                     + f",{s.doy},{float(s.minute)!r}\n")


def python_reference(model, use_wind, threshold, days):
    det = gbt.GbtDetector(model, use_wind, threshold, hybrid=True,
                          persist=config.GBT_PERSIST)
    n = len(feature_names(use_wind, True))
    p, alarm, feats = np.empty(len(days)), np.zeros(len(days), bool), np.full((len(days), n), np.nan)
    for i, (new_day, s) in enumerate(stream.samples(days)):
        if new_day:
            det.reset()
        alarm[i] = det.update(s)
        p[i] = det.p
        if p[i] == p[i]:
            feats[i] = det.x
    return p, alarm, feats


def read_c_output(path, n_features):
    p, alarm, feats = [], [], []
    for line in open(path):
        parts = line.strip().split(",")
        p.append(float(parts[0]))
        alarm.append(parts[1] == "1")
        f = [float(x) for x in parts[2:]]
        feats.append(f if f else [np.nan] * n_features)
    return np.array(p), np.array(alarm), np.array(feats)


def compare(py, c, names):
    (pp, ap, fp), (pc, ac, fc) = py, c
    valid_py, valid_c = ~np.isnan(pp), ~np.isnan(pc)
    both = valid_py & valid_c
    fdiff = np.nanmax(np.abs(fp[both] - fc[both]), axis=0)
    ip, ic = np.flatnonzero(ap), np.flatnonzero(ac)
    shifts = [int(np.min(np.abs(ic - i))) if len(ic) else None
              for i in sorted(set(ip) - set(ic))]
    return {
        "samples": int(len(pp)),
        "valid_samples": int(both.sum()),
        "warm_up_pattern_equal": bool(np.array_equal(valid_py, valid_c)),
        "max_abs_dp": float(np.max(np.abs(pp[both] - pc[both]))),
        "alarms_python": int(ap.sum()),
        "alarms_c": int(ac.sum()),
        "alarm_mismatches": int((ap != ac).sum()),
        "max_abs_feature_diff": {n: float(d) for n, d in zip(names, fdiff)},
        "python_alarms_missing_in_c_nearest_c_alarm_samples": shifts,
    }


def model_structure(booster):
    trees = booster.dump_model()["tree_info"]

    def count(node):
        if "leaf_value" in node:
            return 0, 1
        a, b = count(node["left_child"]), count(node["right_child"])
        return a[0] + b[0] + 1, a[1] + b[1]
    splits, leaves = map(sum, zip(*(count(t["tree_structure"]) for t in trees)))
    return {"trees": len(trees), "split_nodes": splits, "leaves": leaves}


# --- main ---------------------------------------------------------------------------

def main():
    v, seed = config.EXPORT_VARIANT, config.EXPORT_SEED
    hard = v == "hard"
    res_dir = pathlib.Path(f"out/results/{v}/seed{seed}")
    tuned_path = res_dir / "tuned.json"
    if not tuned_path.exists():
        raise SystemExit(f"run first: python -m eval.run --seed {seed}{' --hard' if hard else ''}")
    tuned = json.loads(tuned_path.read_text())
    OUT.mkdir(parents=True, exist_ok=True)
    GEN_DIR.mkdir(parents=True, exist_ok=True)

    days, events = synth.generate(seed, n_days=config.HARD_N_DAYS if hard else config.N_DAYS,
                                  hard=hard)
    parts = split_days(days, events, config.HARD_SPLIT_DAYS if hard else config.SPLIT_DAYS)
    train, test = parts["train"], parts["test"]
    y, use = gbt.sample_targets(*train)
    (GEN_DIR / "nasim_config.h").write_text(config_header())

    models, report = {}, {"variant": v, "seed": seed, "models": {}}
    for tag, use_wind, row in MODELS:
        names = feature_names(use_wind, True)
        thr = tuned[f"{row} p_threshold"]["value"]
        print(f"[{tag}] retraining on {train[0]['date'].nunique()} training days ...", flush=True)
        clf = gbt.train(gbt.build_features(train[0], use_wind, hybrid=True), y, use, seed,
                        names=names, weighting=config.GBT_CLASS_WEIGHT)
        saved = lgb.Booster(model_file=str(res_dir / f"gbt_hybrid_{tag}.txt"))
        same = clf.booster_.model_to_string().split("parameters:")[0] == \
            saved.model_to_string().split("parameters:")[0]
        if not same:
            raise SystemExit(f"[{tag}] retrained model differs from the saved one")
        src = model_source(clf, tag, names, thr, f"Source: {v} synthetic data, seed {seed}.")
        (GEN_DIR / f"nasim_model_{tag}.c").write_text(src)
        models[tag] = (clf, use_wind, thr, names)
        report["models"][tag] = {"row": row, "p_threshold": thr, "features": names,
                                 "identical_to_saved_model": same,
                                 **model_structure(clf.booster_)}

    gcc = find_gcc()
    report["sources_bytes"] = {p.name: p.stat().st_size for p in
                               [C_DIR / "nasim.h", C_DIR / "nasim.c",
                                GEN_DIR / "nasim_config.h", GEN_DIR / "nasim_model_nowind.c",
                                GEN_DIR / "nasim_model_wind.c"]}
    if gcc is None:
        print("C files written to export/c/generated; no gcc found, parity test skipped.")
        (OUT / "export_report.json").write_text(json.dumps(report, indent=2))
        return
    report["gcc"] = subprocess.run([gcc, "--version"], capture_output=True,
                                   text=True).stdout.splitlines()[0]
    inp = OUT / "test_input.csv"
    write_input(test[0], inp)
    exes = {"double": compile_parity(gcc, False), "float": compile_parity(gcc, True)}
    report["object_bytes"] = {"double": object_sizes(gcc, False),
                              "float": object_sizes(gcc, True)}
    for tag, (clf, use_wind, thr, names) in models.items():
        print(f"[{tag}] Python reference on {test[0]['date'].nunique()} test days ...", flush=True)
        py = python_reference(clf, use_wind, thr, test[0])
        for prec, exe in exes.items():
            outp = OUT / f"c_{tag}_{prec}.csv"
            subprocess.run([str(exe), str(int(use_wind)), repr(thr), str(config.GBT_PERSIST),
                            str(inp), str(outp)], check=True)
            c = read_c_output(outp, len(names))
            q = compare(py, c, names)
            q["event_F1_python"] = evaluate(py[1], test)["F1"]
            q["event_F1_c"] = evaluate(c[1], test)["F1"]
            report["models"][tag][f"parity_{prec}"] = q
    (OUT / "export_report.json").write_text(json.dumps(report, indent=2))
    write_markdown(report)
    print((OUT / "parity.md").read_text(encoding="utf-8"))


def write_markdown(r):
    L = [f"# NASIM-GBT export to C - parity report ({r['variant']} synthetic data, seed {r['seed']})",
         "", "**Models trained on SYNTHETIC data: the export pipeline is proven, not the "
         "detector. Retrain on real data before deployment.**", "",
         f"Compiler: {r.get('gcc', '-')}. Held-out test days of the same run, every sample "
         "fed through the Python detector and through the compiled C detector "
         "(features, thermal step, CUSUM core, model, persistence and silence logic).", "",
         "| model | precision | samples (valid) | max abs dp | alarms Py / C | alarm mismatches | worst feature diff | event F1 Py / C |",
         "|---|---|---|---|---|---|---|---|"]
    for tag, m in r["models"].items():
        for prec in ("double", "float"):
            q = m.get(f"parity_{prec}")
            if not q:
                continue
            wf = max(q["max_abs_feature_diff"].items(), key=lambda kv: kv[1])
            L.append(f"| {m['row']} | {prec} | {q['samples']} ({q['valid_samples']}) | "
                     f"{q['max_abs_dp']:.3g} | {q['alarms_python']} / {q['alarms_c']} | "
                     f"{q['alarm_mismatches']} | {wf[0]} {wf[1]:.3g} | "
                     f"{q['event_F1_python']:.3f} / {q['event_F1_c']:.3f} |")
    for tag, m in r["models"].items():
        q = m.get("parity_float")
        if q and q["alarm_mismatches"]:
            L.append("")
            L.append(f"{m['row']}, float: Python alarms missing in C, distance to the "
                     f"nearest C alarm in samples (10 s each): "
                     f"{q['python_alarms_missing_in_c_nearest_c_alarm_samples']}.")
    L += ["", "## Size", "", "| file | source bytes |", "|---|---|"]
    L += [f"| {k} | {b} |" for k, b in r["sources_bytes"].items()]
    if "object_bytes" in r:
        L += ["", "Compiled code + data (x86-64, gcc -Os; an indication only - measure the "
              "ESP32/Xtensa build in task 2):", "", "| object | double | float |", "|---|---|---|"]
        for k in r["object_bytes"]["double"]:
            L.append(f"| {k} | {r['object_bytes']['double'][k]} | {r['object_bytes']['float'][k]} |")
    L += ["", "## Models", ""]
    for tag, m in r["models"].items():
        L.append(f"- **{m['row']}**: {m['trees']} trees, {m['split_nodes']} split nodes, "
                 f"{m['leaves']} leaves; p threshold {m['p_threshold']!r}, persist "
                 f"{config.GBT_PERSIST}; identical to the eval.run model: "
                 f"{m['identical_to_saved_model']}; features: {', '.join(m['features'])}.")
    L += ["", "## float vs double", "",
          "The ESP32 FPU executes single precision (float) in hardware; double is emulated "
          "in software (slower, but one detector update every 10 s costs only a few "
          "thousand operations). The double build reproduces Python (0 alarm "
          "mismatches required). In the float build, rounding error accumulates in the "
          "running CUSUM statistic (cusum_S) and the online thermal model, and the trees "
          "turn tiny feature differences into different branches near a split; most "
          "differing alarms move by a few samples. Recommendation: run features, CUSUM "
          "core and model in double on the ESP32 and measure the update time on the board "
          "(task 2); use float only if that time is too long, then re-run this parity "
          "test and accept the event-level difference explicitly."]
    (OUT / "parity.md").write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()

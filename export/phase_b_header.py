"""Write export/c/generated/phase_b_config.h from the Phase B block of config.py.

    python -m export.phase_b_header

The firmware takes every Phase B value from this generated header; none is typed in the
firmware sources. config.py stays the one place where a [PLACEHOLDER] is replaced
(tests/test_phase_b_flags.py fails if the committed header is not the current one).
Only the logger built with PHASE_B_ENABLED 1 or MARKER_CODES_ENABLED 1 includes the file.
"""
import pathlib

import config
from data.schema import MARKER_CODES

PATH = pathlib.Path(__file__).resolve().parent / "c" / "generated" / "phase_b_config.h"


def _f(x):
    return f"{float(x)!r}f"


def _u(x):
    return f"{int(x)}u"


def header():
    c = config
    if c.PHASE_B_BASELINE_MIN > c.PHASE_B_LOCKOUT_MIN:
        raise ValueError("PHASE_B_BASELINE_MIN must not exceed PHASE_B_LOCKOUT_MIN: an "
                         "event's baseline would overlap the window before it")
    rows = [  # (name, value, comment)
        ("PHASE_B_PLACEHOLDERS_CONFIRMED", int(bool(c.PHASE_B_PLACEHOLDERS_CONFIRMED)),
         "1 only when no [PLACEHOLDER] is left in config.py"),
        ("PHASE_B_DRY_RUN", int(bool(c.PHASE_B_DRY_RUN)), "1 = the pump never runs"),
        ("PHASE_B_BLOCK_SIZE", _u(c.PHASE_B_BLOCK_SIZE), "permuted blocks: half spray, half not"),
        ("PHASE_B_SEED", _u(c.PHASE_B_SEED), "[PLACEHOLDER] allocation sequence"),
        ("PHASE_B_EVENT_WINDOW_MS", _u(c.PHASE_B_EVENT_WINDOW_MIN * 60000), "spike window"),
        ("PHASE_B_LOCKOUT_MS", _u(c.PHASE_B_LOCKOUT_MIN * 60000), "after a window"),
        ("PUMP_DUTY", _f(c.PUMP_DUTY), "[PLACEHOLDER] PWM duty while spraying"),
        ("SPRAY_MAX_MS", _u(c.SPRAY_MAX_S * 1000), "[PLACEHOLDER] longest spray"),
        ("SPRAY_STOP_DROP_C", _f(c.SPRAY_STOP_DROP_C), "[PLACEHOLDER] 0 = not used"),
        ("SPRAY_MIN_DT_WATER_C", _f(c.SPRAY_MIN_DT_WATER_C), "[PLACEHOLDER]"),
        ("SPRAY_MAX_DT_WATER_C", _f(c.SPRAY_MAX_DT_WATER_C), "[PLACEHOLDER] thermal shock"),
        ("SPRAY_MIN_G_WM2", _f(c.SPRAY_MIN_G_WM2), "no event below"),
        ("SPRAY_NEED_T_WATER", int(bool(c.SPRAY_NEED_T_WATER)), "needs TANK_ROM"),
        ("PUMP_I_MAX_A", _f(c.PUMP_I_MAX_A), "[PLACEHOLDER] over-current stop"),
        ("PUMP_NO_FLOW_MS", _u(c.PUMP_NO_FLOW_S * 1000), "[PLACEHOLDER] pump on, no flow pulse"),
        ("PUMP_SAMPLE_MS", _u(c.PUMP_SAMPLE_MS), "pump-power readings"),
        ("SPRAY_HARD_MARGIN_MS", _u(c.SPRAY_HARD_MARGIN_S * 1000),
         "independent cut-off: this long after the longest spray"),
        ("FLOW_PULSES_PER_L", _f(c.FLOW_PULSES_PER_L), "[PLACEHOLDER] flow sensor"),
        ("FLOW_GLITCH_NS", _u(c.FLOW_GLITCH_NS), "[PLACEHOLDER] shorter pulses are ignored"),
        ("FLOW_PIN", int(c.FLOW_PIN), "[PLACEHOLDER] GPIO of the flow pulses"),
        ("PUMP_INA226_ADDR", f"0x{int(c.PUMP_INA226_ADDR):02X}", "[PLACEHOLDER] I2C address"),
        ("PUMP_INA226_PAHUB_CH", int(c.PUMP_INA226_PAHUB_CH), "-1 = directly on the bus"),
        ("PUMP_INA226_SHUNT_OHM", _f(c.PUMP_INA226_SHUNT_OHM), "[PLACEHOLDER]"),
        ("PUMP_INA226_MAX_A", _f(c.PUMP_INA226_MAX_A), "[PLACEHOLDER]"),
        ("TANK_ROM_BYTES", "{" + ", ".join(f"0x{int(b):02X}" for b in c.TANK_ROM) + "}",
         "[PLACEHOLDER] all zero = no tank sensor"),
    ]
    lines = ["/* GENERATED by export/phase_b_header.py from config.py -- do not edit.",
             " * Phase B preparation (randomized spray trial). NOT ADOPTED, no hardware exists.",
             " * [PLACEHOLDER] = not known yet: replace the value in config.py, regenerate. */",
             "#ifndef PHASE_B_CONFIG_H", "#define PHASE_B_CONFIG_H"]
    lines += [f"#define {name} {value}  /* {note} */" for name, value, note in rows]
    lines.append("/* `code` column of /markers.csv (data/schema.py, MARKER_CODES) */")
    lines += [f"#define MARKER_CODE_{text.upper().replace(' ', '_')} {code}"
              for code, text in MARKER_CODES.items()]
    lines += ["#endif", ""]
    return "\n".join(lines)


def main():
    PATH.write_text(header(), encoding="utf-8", newline="\n")
    print(f"-> {PATH}")


if __name__ == "__main__":
    main()

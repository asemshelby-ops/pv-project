"""Export the on-board detectors of a pipeline run to C and check C against Python.

    python -m analysis.export_model --run out/paper_demo/seed5

Reads <run>/raw (logger files) and <run>/results (events.csv, tuned.json, the saved
model). Steps:
  1. retrain on the training days (training is deterministic) and require the result to
     equal the saved model;
  2. write export/c/generated/nasim_model_nowind.c (m2cgen), nasim_config.h (from
     config.py) and nasim_tuned.h (the settings of tuned.json: NASIM's p threshold, the
     threshold rule's rise, the CUSUM's kappa and h). The firmware takes every setting
     from these files; none is typed by hand;
  3. replay EVERY day of the run through the compiled C detectors (export/c/nasim.c, the
     file the logger compiles; double and float builds) and compare, per detector, every
     alarm and its time with the alarms of the Python pipeline (the array rules of
     analysis/detection.py, i.e. what the paper's tables are computed from); for NASIM
     also every probability and feature;
  4. write <run>/results/parity.json (with the time of every alarm that differs) and
     table7_parity.csv.
The on-board check is NOT done here. export/replay.py flashes the board and replays a
test set, but it still builds that set from the pre-10-Nov evaluation (eval/run.py); it
must be pointed at this run's days before the on-board result can be quoted.
The wind model file in export/c/generated is NOT touched: there is no anemometer in this
phase; the file is only linked because the PC harness references its symbol.
"""
import argparse
import json
import pathlib
import subprocess

import lightgbm as lgb
import numpy as np
import pandas as pd

import config
from analysis import detection, ingest
from detect import gbt
from export import run as ex

DETECTORS = ("NASIM-GBT", "Threshold (tuned)", "CUSUM")     # names of analysis/detection.py


def tuned_header(tuned, note):
    """nasim_tuned.h: the detector settings chosen on the validation days of one run."""
    vals = {"P_THRESHOLD": tuned["nasim_p_threshold"],
            "THR_RISE_C": tuned["threshold_rise_C"],
            "CUSUM_KAPPA_C": tuned["cusum_kappa_C_per_sample"],
            "CUSUM_H_C": tuned["cusum_h_C"]}
    lines = ["/* GENERATED by analysis/export_model.py from tuned.json -- do not edit.",
             f" * Source: {note}.",
             " * Settings chosen on the validation days (analysis/detection.py). */",
             "#ifndef NASIM_TUNED_H", "#define NASIM_TUNED_H"]
    lines += [f"#define NASIM_TUNED_{k} {float(v)!r}" for k, v in vals.items()]
    lines += ["#endif", ""]
    return "\n".join(lines)


def alarm_differences(a_py, a_c, when, in_test):
    """Row-by-row comparison of two alarm arrays. `when`: local time text per row."""
    only_py, only_c = np.flatnonzero(a_py & ~a_c), np.flatnonzero(~a_py & a_c)
    return {"alarms Python": int(a_py.sum()), "alarms C": int(a_c.sum()),
            "same row": int((a_py & a_c).sum()),
            "only Python": len(only_py), "only C": len(only_c),
            "alarms Python (test days)": int((a_py & in_test).sum()),
            "mismatches (test days)": int(((a_py != a_c) & in_test).sum()),
            "only_python_times": [when[i] for i in only_py],
            "only_c_times": [when[i] for i in only_c]}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--run", default=f"out/paper_demo/seed{config.EXPORT_SEED}")
    ap.add_argument("--note", default="SYNTHETIC data (hard variant), paper spike definition")
    a = ap.parse_args()
    run, res = pathlib.Path(a.run), pathlib.Path(a.run) / "results"
    tuned = json.loads((res / "tuned.json").read_text())
    thr, seed = tuned["nasim_p_threshold"], config.EXPORT_SEED
    rise_c, kappa, h = (tuned[k] for k in ("threshold_rise_C", "cusum_kappa_C_per_sample",
                                           "cusum_h_C"))
    frame = ingest.detector_frame(ingest.read_logger(run / "raw"))
    events = pd.read_csv(res / "events.csv")
    m = ingest.read_markers(run / "raw" / "markers.csv")[0]
    excluded = ingest.excluded_windows(ingest.join_logsheets(m, run / "raw" / "logsheets")[0])
    parts = detection.split_days(frame["date"].unique())
    train_mask = frame["date"].isin(parts["train"]).to_numpy()
    in_test = frame["date"].isin(parts["test"]).to_numpy()
    seg = frame["segment"].to_numpy()

    print(f"features of {frame['date'].nunique()} days ...", flush=True)
    X = gbt.build_features(frame, False, hybrid=True)
    print(f"retraining on {len(parts['train'])} training days ...", flush=True)
    y, use = gbt.sample_targets(frame[train_mask], detection.training_events(
        events[events["date_local"].isin(parts["train"])], excluded))
    clf = gbt.train(X[train_mask], y, use, seed, names=detection.NAMES,
                    weighting=config.GBT_CLASS_WEIGHT)
    saved = lgb.Booster(model_file=str(res / "nasim_gbt_nowind.txt"))
    same = clf.booster_.model_to_string().split("parameters:")[0] == \
        saved.model_to_string().split("parameters:")[0]
    if not same:
        raise SystemExit("retrained model differs from the saved one")

    ex.GEN_DIR.mkdir(parents=True, exist_ok=True)
    ex.OUT.mkdir(parents=True, exist_ok=True)
    (ex.GEN_DIR / "nasim_config.h").write_text(ex.config_header())
    (ex.GEN_DIR / "nasim_tuned.h").write_text(tuned_header(tuned, a.note))
    (ex.GEN_DIR / "nasim_model_nowind.c").write_text(
        ex.model_source(clf, "nowind", detection.NAMES, thr, f"Source: {a.note}."))

    gcc = ex.find_gcc()
    if gcc is None:
        raise SystemExit("detectors exported, but no gcc found: parity NOT checked")
    # The Python pipeline's alarms, computed as analysis/detection.py computes them.
    ok = ~np.isnan(X).any(axis=1)
    p = np.full(len(frame), np.nan)
    p[ok] = clf.booster_.predict(X[ok])
    py = {"NASIM-GBT": detection.alarm_rule(p, thr, seg, config.GBT_PERSIST),
          "Threshold (tuned)": detection.alarm_rule(
              X[:, detection.NAMES.index("rise_10m")], rise_c, seg),
          "CUSUM": detection.cusum_inc_alarms(detection.filtered_temperature(frame), seg,
                                              kappa, h)}
    when = (frame["date"] + " " + frame["time"]).to_numpy()
    inp = ex.OUT / "paper_all_input.csv"
    ex.write_input(frame, inp)
    rows, detail = [], {}
    for single in (False, True):
        build = "float" if single else "double"
        exe = ex.compile_parity(gcc, single)
        outp = ex.OUT / f"paper_c_{build}.csv"
        subprocess.run([str(exe), "0", repr(float(thr)), str(config.GBT_PERSIST), str(inp),
                        str(outp), repr(float(rise_c)), repr(float(kappa)), repr(float(h))],
                       check=True)
        p_c, a_c, f_c, a_thr, a_cusum = ex.read_c_output(outp, len(detection.NAMES), True)
        r = ex.compare((p, py["NASIM-GBT"], X), (p_c, a_c, f_c), detection.NAMES)
        c = {"NASIM-GBT": a_c, "Threshold (tuned)": a_thr, "CUSUM": a_cusum}
        for name in DETECTORS:
            d = alarm_differences(py[name], c[name], when, in_test)
            detail[f"{build} / {name}"] = {k: d.pop(k) for k in ("only_python_times",
                                                                 "only_c_times")}
            nasim = name == "NASIM-GBT"
            rows.append({"build": build, "detector": name, "samples": r["samples"], **d,
                         "max |dp|": f"{r['max_abs_dp']:.3g}" if nasim else "",
                         "worst feature diff":
                             f"{max(r['max_abs_feature_diff'].values()):.3g}" if nasim else ""})
            print(rows[-1], flush=True)
    table = pd.DataFrame(rows)
    table.to_csv(res / "table7_parity.csv", index=False)
    (res / "parity.json").write_text(json.dumps(
        {"settings": {"nasim_p_threshold": thr, "nasim_persist": config.GBT_PERSIST,
                      "threshold_rise_C": rise_c, "cusum_kappa_C_per_sample": kappa,
                      "cusum_h_C": h},
         "days": int(frame["date"].nunique()), "test_days": len(parts["test"]),
         "identical_to_saved_model": same, "model": ex.model_structure(clf.booster_),
         "builds": rows, "alarms_that_differ": detail,
         "on_board": "not run: needs the ESP32 and an adapted export/replay.py"}, indent=2))
    bad = table[(table["build"] == "double") & (table["only Python"] + table["only C"] > 0)]
    if len(bad):
        raise SystemExit("double build does not reproduce Python: " + ", ".join(bad["detector"]))
    print("double build: every alarm of the three detectors at the same row as in Python")


if __name__ == "__main__":
    main()
